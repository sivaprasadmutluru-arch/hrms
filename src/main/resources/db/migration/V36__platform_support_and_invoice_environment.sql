ALTER TABLE public.billing_invoices ADD COLUMN IF NOT EXISTS live_mode BOOLEAN;
-- Historical rows intentionally remain NULL: their payment environment was not recorded.
CREATE TABLE IF NOT EXISTS public.platform_support_tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version BIGINT NOT NULL DEFAULT 0,
 organization_id BIGINT NOT NULL,
 organization_name VARCHAR(255) NOT NULL,
 subject VARCHAR(200) NOT NULL,
 category VARCHAR(255) NOT NULL,
 priority VARCHAR(255) NOT NULL,
 status VARCHAR(255) NOT NULL,
 created_by VARCHAR(255) NOT NULL,
 assigned_to VARCHAR(255),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 first_response_at TIMESTAMP WITH TIME ZONE,
 resolved_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS platform_support_org_idx ON public.platform_support_tickets(organization_id,updated_at);
CREATE TABLE IF NOT EXISTS public.platform_support_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL,
 author VARCHAR(255) NOT NULL,
 platform_reply BOOLEAN NOT NULL,
 kind VARCHAR(255) NOT NULL,
 body VARCHAR(6000) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS platform_support_message_idx ON public.platform_support_messages(ticket_id,id);

CREATE INDEX IF NOT EXISTS platform_support_queue_idx ON public.platform_support_tickets(updated_at);
CREATE INDEX IF NOT EXISTS platform_support_status_idx ON public.platform_support_tickets(status,updated_at);
