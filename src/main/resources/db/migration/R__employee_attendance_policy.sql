-- Additive, idempotent; no existing employee is exempted and no punches are modified.
DO $policy$
DECLARE tenant text;
BEGIN
    FOR tenant IN SELECT 'public' UNION SELECT schema_name FROM public.companies WHERE schema_name IS NOT NULL LOOP
        IF tenant !~ '^[a-zA-Z0-9_]+$' THEN RAISE EXCEPTION 'Invalid tenant schema'; END IF;
        IF NOT EXISTS (SELECT 1 FROM information_schema.schemata WHERE schema_name = tenant) THEN CONTINUE; END IF;
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.employee_attendance_policies (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            is_active boolean NOT NULL DEFAULT true, created_at timestamp, updated_at timestamp,
            employee_id bigint NOT NULL, company_id bigint NOT NULL,
            attendance_required boolean NOT NULL DEFAULT true, effective_from date NOT NULL,
            reason varchar(500) NOT NULL, changed_by_user_id bigint NOT NULL)', tenant);
        EXECUTE format('CREATE INDEX IF NOT EXISTS employee_attendance_policy_lookup ON %I.employee_attendance_policies (company_id, employee_id, effective_from DESC, id DESC)', tenant);
    END LOOP;
END $policy$;
