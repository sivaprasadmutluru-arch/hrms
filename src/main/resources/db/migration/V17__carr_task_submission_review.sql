-- Additive upgrade; legacy responsibilities retain their previous review policy.
DO $$
DECLARE t record; c record;
BEGIN
 FOR t IN SELECT table_schema FROM information_schema.tables WHERE table_name='carr_responsibilities' AND table_type='BASE TABLE' LOOP
  EXECUTE format('ALTER TABLE %I.carr_responsibilities
   ADD COLUMN IF NOT EXISTS instructions text,
   ADD COLUMN IF NOT EXISTS required_deliverables text,
   ADD COLUMN IF NOT EXISTS requires_review boolean NOT NULL DEFAULT false,
   ADD COLUMN IF NOT EXISTS requires_evidence boolean NOT NULL DEFAULT false,
   ADD COLUMN IF NOT EXISTS assigned_by_user_id bigint,
   ADD COLUMN IF NOT EXISTS assigned_by_name varchar(255),
   ADD COLUMN IF NOT EXISTS reviewer_user_id bigint,
   ADD COLUMN IF NOT EXISTS assigned_at timestamp,
   ADD COLUMN IF NOT EXISTS work_details text,
   ADD COLUMN IF NOT EXISTS blocker_reason text,
   ADD COLUMN IF NOT EXISTS review_feedback text,
   ADD COLUMN IF NOT EXISTS actual_completion_date date,
   ADD COLUMN IF NOT EXISTS submitted_at timestamp,
   ADD COLUMN IF NOT EXISTS completed_at timestamp,
   ADD COLUMN IF NOT EXISTS deadline_notice_date date,
   ADD COLUMN IF NOT EXISTS deadline_notice_kind varchar(20),
   ADD COLUMN IF NOT EXISTS task_version bigint NOT NULL DEFAULT 0',t.table_schema);
  FOR c IN SELECT conname FROM pg_constraint WHERE conrelid=format('%I.carr_responsibilities',t.table_schema)::regclass AND contype='c' AND pg_get_constraintdef(oid) LIKE '%task_status%' LOOP
   EXECUTE format('ALTER TABLE %I.carr_responsibilities DROP CONSTRAINT %I',t.table_schema,c.conname);
  END LOOP;
  EXECUTE format('ALTER TABLE %I.carr_responsibilities ADD CONSTRAINT carr_task_status_check CHECK (task_status IN (''TODO'',''IN_PROGRESS'',''BLOCKED'',''READY_FOR_REVIEW'',''ON_HOLD'',''COMPLETED'',''CANCELLED''))',t.table_schema);
  EXECUTE format('CREATE TABLE IF NOT EXISTS %I.carr_task_attachments (
   id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   created_at timestamp NOT NULL DEFAULT now(), updated_at timestamp NOT NULL DEFAULT now(), is_active boolean NOT NULL DEFAULT true,
   task_id bigint NOT NULL REFERENCES %I.carr_responsibilities(id), uploaded_by_user_id bigint NOT NULL,
   kind varchar(30) NOT NULL CHECK (kind IN (''INSTRUCTION'',''DELIVERABLE'')), filename varchar(255) NOT NULL,
   storage_path varchar(1000) NOT NULL, file_size bigint NOT NULL)',t.table_schema,t.table_schema);
  EXECUTE format('CREATE INDEX IF NOT EXISTS idx_carr_task_attachment ON %I.carr_task_attachments(task_id)',t.table_schema);
 END LOOP;
END $$;
