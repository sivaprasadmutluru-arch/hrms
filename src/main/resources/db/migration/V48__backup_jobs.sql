CREATE TABLE IF NOT EXISTS public.backup_settings (
 id INT PRIMARY KEY CHECK(id=1), database_enabled BOOLEAN NOT NULL DEFAULT true, media_enabled BOOLEAN NOT NULL DEFAULT true,
 drive_enabled BOOLEAN NOT NULL DEFAULT false, schedule_enabled BOOLEAN NOT NULL DEFAULT false,
 frequency VARCHAR(10) NOT NULL DEFAULT 'DAILY', hour INT NOT NULL DEFAULT 2 CHECK(hour BETWEEN 0 AND 23), minute INT NOT NULL DEFAULT 0 CHECK(minute BETWEEN 0 AND 59),
 timezone VARCHAR(80) NOT NULL DEFAULT 'UTC', next_run_at TIMESTAMPTZ, updated_by VARCHAR(255), updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO public.backup_settings(id) VALUES(1) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS public.backup_jobs (
 id UUID PRIMARY KEY, status VARCHAR(30) NOT NULL CHECK(status IN ('QUEUED','RUNNING','SUCCEEDED','PARTIAL','FAILED')),
 source VARCHAR(20) NOT NULL, requested_by VARCHAR(255) NOT NULL, settings_json TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, started_at TIMESTAMPTZ, finished_at TIMESTAMPTZ,
 filename VARCHAR(120), bytes BIGINT, sha256 VARCHAR(64), verified_at TIMESTAMPTZ, error VARCHAR(1000), drive_status VARCHAR(30) NOT NULL DEFAULT 'NOT_REQUESTED', drive_file_id VARCHAR(255)
);
CREATE UNIQUE INDEX IF NOT EXISTS backup_one_active_job ON public.backup_jobs((1)) WHERE status IN ('QUEUED','RUNNING');
