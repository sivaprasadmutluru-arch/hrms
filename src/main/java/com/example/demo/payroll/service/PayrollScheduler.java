package com.example.demo.payroll.service;

import com.example.demo.base.entity.Company;
import com.example.demo.base.repository.CompanyRepository;
import com.example.demo.base.service.EmailService;
import com.example.demo.common.tenant.TenantContext;
import com.example.demo.payroll.entity.Payslip;
import com.example.demo.payroll.entity.PayslipAutoGenerate;
import com.example.demo.payroll.repository.PayslipAutoGenerateRepository;
import com.example.demo.payroll.repository.PayslipRepository;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Component;

import java.time.LocalDate;
import java.time.LocalTime;
import java.time.YearMonth;
import java.util.List;

@Component
@RequiredArgsConstructor
@Slf4j
public class PayrollScheduler {

    private final PayslipAutoGenerateRepository payslipAutoGenerateRepository;
    private final PayrollService payrollService;
    private final PayslipRepository payslipRepository;
    private final EmailService emailService;
    private final CompanyRepository companyRepository;

    /**
     * Runs every minute. Iterates over all tenant schemas and for each company
     * with auto-generate enabled, checks if today's date and current time match
     * the configured day/time, then generates payslips for the previous month.
     */
    @Scheduled(cron = "0 * * * * *")
    public void autoGeneratePayslips() {
        autoGeneratePayslips(false);
    }

    /**
     * Trigger auto-generation across all tenant schemas.
     * @param ignoreDay if true, skips the generateDay/time check (used for manual UI triggers)
     */
    public void autoGeneratePayslips(boolean ignoreDay) {
        LocalDate today = LocalDate.now();
        LocalTime now = LocalTime.now();
        int dayOfMonth = today.getDayOfMonth();
        boolean isLastDay = today.equals(today.withDayOfMonth(today.lengthOfMonth()));

        List<Company> headOffices = companyRepository.findByCompanyType(Company.CompanyType.HEAD_OFFICE);
        log.info("[PayrollScheduler] Tick — date={} time={}:{} | tenants={}",
                today, now.getHour(), String.format("%02d", now.getMinute()), headOffices.size());

        for (Company headOffice : headOffices) {
            String schema = headOffice.getSchemaName();
            if (schema == null || schema.isBlank()) {
                log.warn("[PayrollScheduler] HEAD_OFFICE company {} has no schema, skipping", headOffice.getId());
                continue;
            }

            try {
                TenantContext.setTenant(schema);
                processSchema(schema, today, now, dayOfMonth, isLastDay, ignoreDay);
            } finally {
                TenantContext.clear();
            }
        }
    }

    private void processSchema(String schema, LocalDate today, LocalTime now,
                               int dayOfMonth, boolean isLastDay, boolean ignoreDay) {
        List<PayslipAutoGenerate> all = payslipAutoGenerateRepository.findAll();
        List<PayslipAutoGenerate> configs = all.stream()
                .filter(c -> Boolean.TRUE.equals(c.getAutoGenerate()))
                .toList();

        log.info("[PayrollScheduler] Schema '{}' — total configs={} enabled={}", schema, all.size(), configs.size());

        for (PayslipAutoGenerate config : configs) {
            Long companyId = config.getCompany().getId();
            if (!ignoreDay && !shouldRunNow(config, dayOfMonth, isLastDay, now)) {
                log.info("[PayrollScheduler] Skipping company {} (schema={}) — day='{}' time='{}' (now={}/{})",
                        companyId, schema, config.getGenerateDay(), config.getGenerateTime(),
                        dayOfMonth, now.getHour() + ":" + String.format("%02d", now.getMinute()));
                continue;
            }

            YearMonth previousMonth = YearMonth.from(today).minusMonths(1);
            LocalDate startDate = previousMonth.atDay(1);
            LocalDate endDate = previousMonth.atEndOfMonth();

            try {
                log.info("[PayrollScheduler] Auto-generating payslips for company {} (schema={}) period {} to {}",
                        companyId, schema, startDate, endDate);
                List<Payslip> generated = payrollService.generateBulkPayslips(companyId, startDate, endDate);
                generated.forEach(p -> p.setAutoGenerated(true));
                payslipRepository.saveAll(generated);
                log.info("[PayrollScheduler] Generated {} payslips for company {} (schema={})",
                        generated.size(), companyId, schema);

                sendNotification(config, companyId, previousMonth, startDate, endDate);
            } catch (Exception e) {
                log.error("[PayrollScheduler] Generation failed for company {} (schema={}): {}",
                        companyId, schema, e.getMessage(), e);
            }
        }
    }

    private boolean shouldRunNow(PayslipAutoGenerate config, int dayOfMonth, boolean isLastDay, LocalTime now) {
        Long companyId = config.getCompany().getId();
        String generateDay = config.getGenerateDay();
        if (generateDay == null || generateDay.isBlank()) return false;

        boolean dayMatches;
        if ("last day".equalsIgnoreCase(generateDay.trim())) {
            dayMatches = isLastDay;
        } else {
            try {
                dayMatches = Integer.parseInt(generateDay.trim()) == dayOfMonth;
            } catch (NumberFormatException e) {
                log.warn("[PayrollScheduler] Invalid generateDay '{}' for company {}", generateDay, companyId);
                return false;
            }
        }
        if (!dayMatches) return false;

        String generateTime = config.getGenerateTime();
        if (generateTime == null || generateTime.isBlank()) return now.getHour() == 0 && now.getMinute() == 0;
        try {
            LocalTime target = LocalTime.parse(generateTime);
            return now.getHour() == target.getHour() && now.getMinute() == target.getMinute();
        } catch (Exception e) {
            log.warn("[PayrollScheduler] Invalid generateTime '{}' for company {}", generateTime, companyId);
            return false;
        }
    }

    private void sendNotification(PayslipAutoGenerate config, Long companyId,
                                  YearMonth previousMonth, LocalDate startDate, LocalDate endDate) {
        String email = config.getNotifyEmail();
        if (email == null || email.isBlank()) return;
        try {
            String subject = "Payslips Auto-Generated for " + previousMonth;
            String body = "<p>Payslips for the period <strong>" + startDate + " to " + endDate
                    + "</strong> have been automatically generated for all active employees.</p>";
            emailService.sendEmail(companyId, email, subject, body, null);
        } catch (Exception e) {
            log.warn("[PayrollScheduler] Failed to send notification for company {}: {}", companyId, e.getMessage());
        }
    }
}
