package com.example.demo.payroll.repository;

import com.example.demo.payroll.entity.Payslip;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.JpaSpecificationExecutor;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;

import java.time.LocalDate;
import java.util.List;
import java.util.Optional;

@Repository
public interface PayslipRepository extends JpaRepository<Payslip, Long>, JpaSpecificationExecutor<Payslip> {

    @Query("SELECT p FROM Payslip p LEFT JOIN FETCH p.employee e LEFT JOIN FETCH e.department LEFT JOIN FETCH p.company")
    List<Payslip> findAllWithAssociations();

    @Query("SELECT p FROM Payslip p LEFT JOIN FETCH p.employee e LEFT JOIN FETCH e.department LEFT JOIN FETCH p.company " +
           "WHERE p.company.id IN :companyIds")
    List<Payslip> findAllWithAssociationsByCompanyIdIn(@Param("companyIds") List<Long> companyIds);

    @Query("SELECT p FROM Payslip p LEFT JOIN FETCH p.employee e LEFT JOIN FETCH e.department LEFT JOIN FETCH p.company " +
           "WHERE e.id = :employeeId")
    List<Payslip> findByEmployeeId(@Param("employeeId") Long employeeId);

    @Query("SELECT p FROM Payslip p LEFT JOIN FETCH p.employee e LEFT JOIN FETCH e.department LEFT JOIN FETCH p.company WHERE p.id = :id")
    Optional<Payslip> findByIdWithAssociations(@Param("id") Long id);

    boolean existsByEmployeeIdAndStartDateAndEndDate(Long employeeId, LocalDate startDate, LocalDate endDate);

    List<Payslip> findByCompanyId(Long companyId);
    List<Payslip> findByCompanyIdAndStatus(Long companyId, Payslip.PayslipStatus status);
    List<Payslip> findByEmployeeIdAndStartDateBetween(Long employeeId, LocalDate from, LocalDate to);

    /** Count payslips that include at least one of the given installment deduction IDs (mirrors GCP installment_ratio) */
    @Query("SELECT COUNT(DISTINCT p) FROM Payslip p JOIN p.installmentIds d WHERE d.id IN :deductionIds")
    long countByInstallmentIdIn(@Param("deductionIds") List<Long> deductionIds);

    @Query("SELECT p FROM Payslip p LEFT JOIN FETCH p.employee e LEFT JOIN FETCH e.department LEFT JOIN FETCH p.company " +
           "WHERE p.autoGenerated = :autoGenerated")
    List<Payslip> findAllWithAssociationsByAutoGenerated(@Param("autoGenerated") boolean autoGenerated);

    @Query("SELECT p FROM Payslip p LEFT JOIN FETCH p.employee e LEFT JOIN FETCH e.department LEFT JOIN FETCH p.company " +
           "WHERE p.company.id IN :companyIds AND p.autoGenerated = :autoGenerated")
    List<Payslip> findAllWithAssociationsByCompanyIdInAndAutoGenerated(
            @Param("companyIds") List<Long> companyIds,
            @Param("autoGenerated") boolean autoGenerated);
}
