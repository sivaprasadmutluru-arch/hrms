package com.example.demo.report.controller;

import com.example.demo.auth.security.UserPrincipal;
import com.example.demo.report.dto.GenerateReportRequest;
import com.example.demo.report.entity.GeneratedReport;
import com.example.demo.report.service.ReportRepositoryService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;
import org.springframework.format.annotation.DateTimeFormat;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.*;

import java.time.LocalDate;
import java.util.Map;

/**
 * RPT-005: central Reports repository — generate, list/filter (grouped client-side into
 * Report Type / Year / Month / Created Date), rename, archive, and re-download report records.
 *
 * Generation stays restricted to admin/manager roles (it queries and exports company-wide
 * data); listing and downloading are additionally open to EMPLOYEE, since a self-scoped
 * employee may want to see/re-download reports generated about them specifically — the
 * service layer restricts what a self-scoped caller can actually see or touch to their own
 * employee-linked records.
 */
@RestController
@RequestMapping("/api/reports/repository")
@RequiredArgsConstructor
@Tag(name = "Reports Repository")
public class ReportRepositoryController {

    private final ReportRepositoryService reportRepositoryService;

    @PostMapping("/generate")
    @PreAuthorize("hasAnyRole('PLATFORM_SUPER_ADMIN', 'ENTERPRISE_ADMIN', 'BRANCH_ADMIN', 'HR_MANAGER', 'ACCOUNTANT')")
    @Operation(summary = "Generate a report, store it, and record it in the central repository")
    public ResponseEntity<GeneratedReport> generate(
            @AuthenticationPrincipal UserPrincipal principal,
            @Valid @RequestBody GenerateReportRequest request) {
        String name = (principal.getUsername() != null ? principal.getUsername() : "").trim();
        GeneratedReport record = reportRepositoryService.generate(request, principal.getId(), name);
        return ResponseEntity.ok(record);
    }

    @GetMapping
    @PreAuthorize("isAuthenticated()")
    @Operation(summary = "List/filter generated reports (Report Type, Company, Employee, Department, Year, Month, Date range, Generated By, Status)")
    public ResponseEntity<Page<GeneratedReport>> list(
            @RequestParam(required = false) GeneratedReport.ReportType reportType,
            @RequestParam(required = false) Long companyId,
            @RequestParam(required = false) Long employeeId,
            @RequestParam(required = false) Long departmentId,
            @RequestParam(required = false) Integer year,
            @RequestParam(required = false) Integer month,
            @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate from,
            @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate to,
            @RequestParam(required = false) String generatedBy,
            @RequestParam(required = false) GeneratedReport.ReportStatus status,
            @RequestParam(defaultValue = "false") boolean includeArchived,
            @RequestParam(defaultValue = "0") int page,
            @RequestParam(defaultValue = "50") int size) {
        Page<GeneratedReport> result = reportRepositoryService.list(
                reportType, companyId, employeeId, departmentId, year, month, from, to,
                generatedBy, status, includeArchived, PageRequest.of(page, size));
        return ResponseEntity.ok(result);
    }

    @GetMapping("/{id}/download")
    @PreAuthorize("isAuthenticated()")
    @Operation(summary = "Download a previously generated report by ID (does not regenerate or duplicate it)")
    public ResponseEntity<byte[]> download(@PathVariable Long id) {
        byte[] bytes = reportRepositoryService.download(id);
        return ResponseEntity.ok()
                .header(HttpHeaders.CONTENT_DISPOSITION, "attachment; filename=\"report-" + id + ".xlsx\"")
                .contentType(MediaType.parseMediaType("application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"))
                .body(bytes);
    }

    @PatchMapping("/{id}/rename")
    @PreAuthorize("hasAnyRole('PLATFORM_SUPER_ADMIN', 'ENTERPRISE_ADMIN', 'BRANCH_ADMIN', 'HR_MANAGER', 'ACCOUNTANT')")
    @Operation(summary = "Rename a report (where permitted by the caller's access scope)")
    public ResponseEntity<GeneratedReport> rename(@PathVariable Long id, @RequestBody Map<String, String> body) {
        return ResponseEntity.ok(reportRepositoryService.rename(id, body.get("reportName")));
    }

    @PatchMapping("/{id}/archive")
    @PreAuthorize("hasAnyRole('PLATFORM_SUPER_ADMIN', 'ENTERPRISE_ADMIN', 'BRANCH_ADMIN', 'HR_MANAGER', 'ACCOUNTANT')")
    @Operation(summary = "Archive a report — hidden from the default list, still searchable/downloadable")
    public ResponseEntity<GeneratedReport> archive(@PathVariable Long id) {
        return ResponseEntity.ok(reportRepositoryService.setArchived(id, true));
    }

    @PatchMapping("/{id}/unarchive")
    @PreAuthorize("hasAnyRole('PLATFORM_SUPER_ADMIN', 'ENTERPRISE_ADMIN', 'BRANCH_ADMIN', 'HR_MANAGER', 'ACCOUNTANT')")
    @Operation(summary = "Restore an archived report to the default list")
    public ResponseEntity<GeneratedReport> unarchive(@PathVariable Long id) {
        return ResponseEntity.ok(reportRepositoryService.setArchived(id, false));
    }
}
